CREATE SCHEMA IF NOT EXISTS marketplace;

CREATE TABLE IF NOT EXISTS marketplace.job_posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employer_id BIGINT NOT NULL REFERENCES public.user_accounts(id) ON DELETE CASCADE,
    title VARCHAR(140) NOT NULL,
    company_name VARCHAR(120) NOT NULL,
    category VARCHAR(100) NOT NULL,
    city VARCHAR(100) NOT NULL,
    address VARCHAR(180) NOT NULL,
    pay_min NUMERIC(12, 2) NOT NULL CHECK (pay_min > 0),
    pay_max NUMERIC(12, 2) NOT NULL CHECK (pay_max >= pay_min),
    pay_unit VARCHAR(20) NOT NULL CHECK (pay_unit IN ('HOUR', 'SHIFT', 'MONTH')),
    schedule VARCHAR(160) NOT NULL,
    employment_type VARCHAR(60) NOT NULL,
    description TEXT NOT NULL,
    requirements JSONB NOT NULL DEFAULT '[]'::jsonb,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'HIRED', 'COMPLETED')),
    published_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS marketplace.applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES marketplace.job_posts(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES public.user_accounts(id) ON DELETE CASCADE,
    introduction TEXT NOT NULL,
    resume_url VARCHAR(2048) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED')),
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (job_id, student_id)
);

CREATE TABLE IF NOT EXISTS marketplace.reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES marketplace.job_posts(id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES public.user_accounts(id) ON DELETE CASCADE,
    target_id BIGINT NOT NULL REFERENCES public.user_accounts(id) ON DELETE CASCADE,
    author_role VARCHAR(20) NOT NULL CHECK (author_role IN ('STUDENT', 'EMPLOYER')),
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment VARCHAR(800) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (author_id <> target_id),
    UNIQUE (job_id, author_id)
);

CREATE TABLE IF NOT EXISTS marketplace.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.user_accounts(id) ON DELETE CASCADE,
    job_id BIGINT REFERENCES marketplace.job_posts(id) ON DELETE SET NULL,
    application_id BIGINT REFERENCES marketplace.applications(id) ON DELETE SET NULL,
    event_type VARCHAR(40) NOT NULL,
    title VARCHAR(160) NOT NULL,
    message VARCHAR(500) NOT NULL,
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS marketplace.saved_jobs (
    student_id BIGINT NOT NULL REFERENCES public.user_accounts(id) ON DELETE CASCADE,
    job_id BIGINT NOT NULL REFERENCES marketplace.job_posts(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (student_id, job_id)
);

CREATE INDEX IF NOT EXISTS idx_job_posts_status_city_category
    ON marketplace.job_posts (status, city, category);
CREATE INDEX IF NOT EXISTS idx_job_posts_employer_created
    ON marketplace.job_posts (employer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_applications_student_submitted
    ON marketplace.applications (student_id, submitted_at DESC);
CREATE INDEX IF NOT EXISTS idx_applications_job_status
    ON marketplace.applications (job_id, status, submitted_at DESC);
CREATE INDEX IF NOT EXISTS idx_reviews_target_created
    ON marketplace.reviews (target_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_notifications_user_unread
    ON marketplace.notifications (user_id, created_at DESC)
    WHERE read_at IS NULL;